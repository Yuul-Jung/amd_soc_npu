#define ROR(x, n) (((x) >> (n)) | ((x) << (32 - (n))))

static void sha_block(sha256_t *s, const uint8_t *p)
{
    uint32_t w[64], a[8];
    for (int i = 0; i < 16; i++) w[i] = (uint32_t)p[4 * i] << 24 | (uint32_t)p[4 * i + 1] << 16 | (uint32_t)p[4 * i + 2] << 8 | p[4 * i + 3];
    for (int i = 16; i < 64; i++)
        w[i] = w[i - 16] + (ROR(w[i - 15], 7) ^ ROR(w[i - 15], 18) ^ (w[i - 15] >> 3)) + w[i - 7] + (ROR(w[i - 2], 17) ^ ROR(w[i - 2], 19) ^ (w[i - 2] >> 10));
    for (int i = 0; i < 8; i++) a[i] = s->h[i];
    for (int i = 0; i < 64; i++) {
        uint32_t t1 = a[7] + (ROR(a[4], 6) ^ ROR(a[4], 11) ^ ROR(a[4], 25)) + ((a[4] & a[5]) ^ (~a[4] & a[6])) + K[i] + w[i];
        uint32_t t2 = (ROR(a[0], 2) ^ ROR(a[0], 13) ^ ROR(a[0], 22)) + ((a[0] & a[1]) ^ (a[0] & a[2]) ^ (a[1] & a[2]));
        for (int k = 7; k > 0; k--) a[k] = a[k - 1];
        a[4] += t1; a[0] = t1 + t2;
    }
    for (int i = 0; i < 8; i++) s->h[i] += a[i];
}

void sha256_init(sha256_t *s)
{
    static const uint32_t H0[8] = {0x6a09e667,0xbb67ae85,0x3c6ef372,0xa54ff53a,0x510e527f,0x9b05688c,0x1f83d9ab,0x5be0cd19};
    for (int i = 0; i < 8; i++) s->h[i] = H0[i];
    s->len = 0; s->used = 0;
}

void sha256_update(sha256_t *s, const uint8_t *p, size_t n)
{
    s->len += n;
    while (n--) { s->buf[s->used++] = *p++; if (s->used == 64) { sha_block(s, s->buf); s->used = 0; } }
}

void sha256_final(sha256_t *s, uint8_t out[32])
{
    uint64_t bits = s->len * 8; uint8_t pad = 0x80, z = 0;
    sha256_update(s, &pad, 1);
    while (s->used != 56) sha256_update(s, &z, 1);
    for (int i = 7; i >= 0; i--) { uint8_t b = (uint8_t)(bits >> (8 * i)); sha256_update(s, &b, 1); }
    for (int i = 0; i < 32; i++) out[i] = (uint8_t)(s->h[i / 4] >> (24 - 8 * (i % 4)));
}

void hmac_sha256(const uint8_t *key, size_t klen, const uint8_t *msg, size_t n, uint8_t out[32])
{
    uint8_t k0[64] = {0}, pad[64], inner[32]; sha256_t s;
    if (klen > 64) { sha256_init(&s); sha256_update(&s, key, klen); sha256_final(&s, k0); }
    else for (size_t i = 0; i < klen; i++) k0[i] = key[i];
    for (int i = 0; i < 64; i++) pad[i] = k0[i] ^ 0x36;
    sha256_init(&s); sha256_update(&s, pad, 64); sha256_update(&s, msg, n); sha256_final(&s, inner);
    for (int i = 0; i < 64; i++) pad[i] = k0[i] ^ 0x5c;
    sha256_init(&s); sha256_update(&s, pad, 64); sha256_update(&s, inner, 32); sha256_final(&s, out);
}

int ct_equal(const uint8_t *a, const uint8_t *b, size_t n)
{
    uint8_t d = 0;
    for (size_t i = 0; i < n; i++) d |= a[i] ^ b[i];
    return d == 0;
}
