static uint8_t xt(uint8_t x) { return (uint8_t)((x << 1) ^ ((x >> 7) * 0x1b)); }

void aes128_encrypt_block(const uint8_t key[16], const uint8_t in[16], uint8_t out[16])
{
    uint8_t rk[176], s[16], t[16], rcon = 1;
    for (int i = 0; i < 16; i++) rk[i] = key[i];
    for (int i = 16; i < 176; i += 4) {                         /* 키 확장 */
        uint8_t w[4] = {rk[i - 4], rk[i - 3], rk[i - 2], rk[i - 1]};
        if (i % 16 == 0) {
            uint8_t x = w[0];
            w[0] = SBOX[w[1]] ^ rcon; w[1] = SBOX[w[2]]; w[2] = SBOX[w[3]]; w[3] = SBOX[x];
            rcon = xt(rcon);
        }
        for (int k = 0; k < 4; k++) rk[i + k] = rk[i - 16 + k] ^ w[k];
    }
    for (int i = 0; i < 16; i++) s[i] = in[i] ^ rk[i];
    for (int r = 1; r <= 10; r++) {
        for (int i = 0; i < 16; i++) t[i] = SBOX[s[(i + 4 * (i % 4)) % 16]];   /* SubBytes + ShiftRows (열 우선) */
        if (r != 10)
            for (int c = 0; c < 4; c++) {                        /* MixColumns */
                uint8_t *a = t + 4 * c, x = a[0] ^ a[1] ^ a[2] ^ a[3], a0 = a[0];
                a[0] ^= x ^ xt(a[0] ^ a[1]); a[1] ^= x ^ xt(a[1] ^ a[2]);
                a[2] ^= x ^ xt(a[2] ^ a[3]); a[3] ^= x ^ xt(a[3] ^ a0);
            }
        for (int i = 0; i < 16; i++) s[i] = t[i] ^ rk[16 * r + i];
    }
    for (int i = 0; i < 16; i++) out[i] = s[i];
}

void aes128_ctr(const uint8_t key[16], const uint8_t iv[16], const uint8_t *in, uint8_t *out, size_t n)
{
    uint8_t ctr[16], ks[16];
    for (int i = 0; i < 16; i++) ctr[i] = iv[i];
    for (size_t off = 0; off < n; off += 16) {
        aes128_encrypt_block(key, ctr, ks);
        for (size_t i = 0; i < 16 && off + i < n; i++) out[off + i] = in[off + i] ^ ks[i];
        for (int i = 15; i >= 0 && ++ctr[i] == 0; i--) { }      /* 128비트 카운터 +1 */
    }
}

